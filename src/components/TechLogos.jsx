// Name to key matcher
export function getTechKey(name = '') {
  const n = name.toLowerCase().trim()
  if (n.includes('react')) return 'react'
  if (n.includes('typescript')) return 'typescript'
  if (n.includes('javascript') || n === 'js') return 'javascript'
  if (n.includes('node')) return 'nodejs'
  if (n.includes('mongo')) return 'mongodb'
  if (n.includes('express')) return 'express'
  if (n.includes('java') && !n.includes('javascript')) return 'java'
  if (n.includes('git') && !n.includes('hub')) return 'git'
  if (n.includes('github')) return 'github'
  if (n.includes('aws')) return 'aws'
  if (n.includes('mysql') || n.includes('sql') || n.includes('relational') || n.includes('dbms')) return 'mysql'
  if (n.includes('gemini') || n.includes('llama') || n.includes('groq') || n.includes('agentic')) return 'gemini'
  if (n.includes('vite')) return 'vite'
  if (n.includes('postman')) return 'postman'
  if (n.includes('jwt') || n.includes('auth') || n.includes('rbac') || n.includes('security')) return 'jwt'
  if (n.includes('html')) return 'html5'
  if (n.includes('css')) return 'css3'
  if (n.includes('bootstrap')) return 'bootstrap'
  if (n.includes('tailwind')) return 'tailwind'
  if (n.includes('api')) return 'api'
  if (n.includes('data') || n.includes('nosql')) return 'database'
  if (n.includes('cloud')) return 'cloud'
  if (n.includes('ai') || n.includes('llm') || n.includes('prompt')) return 'gemini'
  return 'code'
}

export default function TechLogo({ name, size = 16, className = '', style = {} }) {
  const key = getTechKey(name)
  const item = techLogos[key] || techLogos.code

  return (
    <span
      className={`tech-logo-icon ${className}`}
      style={{
        display: 'inline-flex',
        alignItems: 'center',
        justifyContent: 'center',
        width: size,
        height: size,
        flexShrink: 0,
        ...style
      }}
    >
      {React.cloneElement(item.component, {
        width: size,
        height: size,
        style: { width: size, height: size }
      })}
    </span>
  )
}
